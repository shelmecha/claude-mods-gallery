// Builds hooks/nerdfont-data.js from the Nerd Fonts glyphnames.json.
// Get it: https://raw.githubusercontent.com/ryanoasis/nerd-fonts/master/glyphnames.json
// Run:    node scripts/build-nerdfont-data.mjs <path/to/glyphnames.json> [out.js]
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const [src, out = fileURLToPath(new URL('../hooks/nerdfont-data.js', import.meta.url))] = process.argv.slice(2)
if (!src) { console.error('usage: node scripts/build-nerdfont-data.mjs <glyphnames.json> [out.js]'); process.exit(1) }

const json = JSON.parse(readFileSync(src, 'utf8'))
const meta = json.METADATA ?? {}
const sets = {}
let count = 0
for (const [id, g] of Object.entries(json)) {
  if (id === 'METADATA') continue
  const at = id.indexOf('-')
  const set = id.slice(0, at), name = id.slice(at + 1)
  if (!/^[0-9a-f]{4,6}$/i.test(g?.code ?? '') || !/^[\w-]+$/.test(name)) throw new Error(`bad entry ${id}`)
  ;(sets[set] ??= []).push([parseInt(g.code, 16), name])
  count++
}
const keys = Object.keys(sets).sort()
const lines = keys.map((k) => {
  const list = sets[k].sort((a, b) => a[0] - b[0] || a[1].localeCompare(b[1]))
  return `  ${JSON.stringify(k)}: ${JSON.stringify(list.map(([c, n]) => c.toString(16) + ' ' + n).join(' '))},`
})
writeFileSync(out, `// Generated by scripts/build-nerdfont-data.mjs. Do not edit.
// Nerd Fonts ${meta.version} (${meta.date}), glyphnames.json from github.com/ryanoasis/nerd-fonts, ${count} glyphs.
// Each set is "hexcode name hexcode name ...".
export const NF_VERSION = ${JSON.stringify(meta.version ?? '')}
export const NF_SETS = {
${lines.join('\n')}
}
`)
console.log(`${count} glyphs in ${keys.length} sets -> ${out}`)
